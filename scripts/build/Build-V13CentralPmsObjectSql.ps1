[CmdletBinding()]
param(
    [string]$RepoRoot,
    [string]$ApplyOrderPath = 'objects\v13-central-pms-object-apply-order.txt',
    [string]$OutputPath = 'build\generated\v13-central-pms-alignment.generated.sql'
)

$ErrorActionPreference = 'Stop'
if ([string]::IsNullOrWhiteSpace($RepoRoot)) {
    $scriptRoot = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
    $RepoRoot = (Resolve-Path (Join-Path $scriptRoot '..\..')).Path
}$applyOrderFullPath = Join-Path $RepoRoot $ApplyOrderPath
if (-not (Test-Path -LiteralPath $applyOrderFullPath)) {
    throw "Apply-order file not found: $applyOrderFullPath"
}

$outputFullPath = Join-Path $RepoRoot $OutputPath
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $outputFullPath) | Out-Null

$paths = Get-Content -LiteralPath $applyOrderFullPath |
    ForEach-Object { $_.Trim() } |
    Where-Object { $_ -and -not $_.StartsWith('#') }

$seen = @{}
foreach ($path in $paths) {
    if ($seen.ContainsKey($path)) {
        throw "Duplicate apply-order entry: $path"
    }
    $seen[$path] = $true

    $full = Join-Path $RepoRoot ($path -replace '/', [IO.Path]::DirectorySeparatorChar)
    if (-not (Test-Path -LiteralPath $full)) {
        throw "Apply-order object file not found: $path"
    }
}

$header = @(
    '-- <auto-generated>',
    '-- ExitPass v1.3 Central PMS alignment generated from object source files.',
    '-- Source apply order: objects/v13-central-pms-object-apply-order.txt',
    '-- Do not edit this generated artifact directly. Edit objects/** first.',
    '-- Migrations remain deployment/change-history artifacts.',
    '-- </auto-generated>',
    ''
) -join "`r`n"

Set-Content -LiteralPath $outputFullPath -Value $header -Encoding UTF8
foreach ($path in $paths) {
    $full = Join-Path $RepoRoot ($path -replace '/', [IO.Path]::DirectorySeparatorChar)
    Add-Content -LiteralPath $outputFullPath -Value "`r`n-- ============================================================================`r`n-- Source object: $path`r`n-- ============================================================================`r`n" -Encoding UTF8
    Add-Content -LiteralPath $outputFullPath -Value (Get-Content -LiteralPath $full -Raw).TrimEnd() -Encoding UTF8
    Add-Content -LiteralPath $outputFullPath -Value "`r`n" -Encoding UTF8
}

Write-Host "Generated $OutputPath from $($paths.Count) object source files."


