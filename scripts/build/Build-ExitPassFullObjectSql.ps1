[CmdletBinding()]
param(
    [string]$RepoRoot,
    [string]$ApplyOrderPath = 'objects\exitpass-full-object-apply-order.txt',
    [string]$OutputPath = 'build\generated\exitpass-full-object.generated.sql'
)

$ErrorActionPreference = 'Stop'
if ([string]::IsNullOrWhiteSpace($RepoRoot)) {
    $scriptRoot = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
    $RepoRoot = (Resolve-Path (Join-Path $scriptRoot '..\..')).Path
}

$applyOrderFullPath = Join-Path $RepoRoot $ApplyOrderPath
if (-not (Test-Path -LiteralPath $applyOrderFullPath)) {
    throw "Apply-order file not found: $applyOrderFullPath"
}

$outputFullPath = Join-Path $RepoRoot $OutputPath
$tempOutputFullPath = $outputFullPath + '.tmp'
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $outputFullPath) | Out-Null

$paths = Get-Content -LiteralPath $applyOrderFullPath |
    ForEach-Object { $_.Trim() } |
    Where-Object { $_ -and -not $_.StartsWith('#') }

$seen = @{}
foreach ($path in $paths) {
    if ($seen.ContainsKey($path)) { throw "Duplicate apply-order entry: $path" }
    $seen[$path] = $true
    $full = Join-Path $RepoRoot ($path -replace '/', [IO.Path]::DirectorySeparatorChar)
    if (-not (Test-Path -LiteralPath $full)) { throw "Apply-order object file not found: $path" }
}

$encoding = New-Object System.Text.UTF8Encoding($false)
$writer = [System.IO.StreamWriter]::new($tempOutputFullPath, $false, $encoding)
try {
    $writer.WriteLine('-- <auto-generated>')
    $writer.WriteLine('-- ExitPass full database generated from object source files.')
    $writer.WriteLine('-- Source apply order: objects/exitpass-full-object-apply-order.txt')
    $writer.WriteLine('-- Do not edit this generated artifact directly. Edit objects/** first.')
    $writer.WriteLine('-- Migrations remain deployment/change-history artifacts.')
    $writer.WriteLine('-- </auto-generated>')
    $writer.WriteLine()

    foreach ($path in $paths) {
        $full = Join-Path $RepoRoot ($path -replace '/', [IO.Path]::DirectorySeparatorChar)
        $writer.WriteLine()
        $writer.WriteLine('-- ============================================================================')
        $writer.WriteLine("-- Source object: $path")
        $writer.WriteLine('-- ============================================================================')
        $writer.WriteLine((Get-Content -LiteralPath $full -Raw).TrimEnd())
        $writer.WriteLine()
    }
}
finally {
    $writer.Dispose()
}

Move-Item -LiteralPath $tempOutputFullPath -Destination $outputFullPath -Force
Write-Host "Generated $OutputPath from $($paths.Count) object source files."
